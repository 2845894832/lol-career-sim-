def crop_bottom(src, dst):
    """把截图底部多余的空白底色裁掉，避免文档里出现半页黑块。"""
    im = Image.open(src).convert("RGB")
    w, h = im.size
    bg = im.getpixel((2, 2))
    last = h - 1
    while last > 0:
        row = [im.getpixel((x, last)) for x in range(0, w, 7)]
        if any(abs(p[0] - bg[0]) + abs(p[1] - bg[1]) + abs(p[2] - bg[2]) > 24 for p in row):
            break
        last -= 1
    im.crop((0, 0, w, min(h, last + 24))).save(dst)
    return dst


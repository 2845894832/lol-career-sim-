def fill_sheet(ws, head, rows, widths, note=None):
    ws.append(head)
    for c in range(1, len(head) + 1):
        cell = ws.cell(row=1, column=c)
        cell.font = Font(name="微软雅黑", size=10, bold=True, color="FFFFFF")
        cell.fill = PatternFill("solid", fgColor=NAVY)
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    for r in rows:
        ws.append(r)
    for i, row in enumerate(ws.iter_rows(min_row=2, max_row=ws.max_row, max_col=len(head))):
        for cell in row:
            cell.font = Font(name="微软雅黑", size=9.5)
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER
            if i % 2 == 1:
                cell.fill = PatternFill("solid", fgColor=GREY)
    for idx, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(idx)].width = w
    ws.freeze_panes = "A2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(head))}{ws.max_row}"
    ws.row_dimensions[1].height = 30
    if note:
        r = ws.max_row + 2
        ws.cell(row=r, column=1, value=note).font = Font(name="微软雅黑", size=9, color="8B95A3")


